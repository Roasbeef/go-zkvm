//go:build ignore

// gen_blobs converts RISC Zero bigint2 program blobs into Go word arrays.
// Word arrays keep the blobs 4-byte aligned, which the bigint2 ecall needs.
//
// Usage: go run gen_blobs.go <risc0 checkout> > blobs.go
package main

import (
	"crypto/sha256"
	"encoding/binary"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

var blobs = []struct {
	name string
	path string
}{
	{"modMul256Blob", "risc0/bigint2/src/field/modmul_256.blob"},
	{"modInv256Blob", "risc0/bigint2/src/field/modinv_256.blob"},
	{"ecAdd256Blob", "risc0/bigint2/src/ec/ec_add_256.blob"},
	{"ecDouble256Blob", "risc0/bigint2/src/ec/ec_double_256.blob"},
}

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: gen_blobs <risc0 checkout>")
		os.Exit(2)
	}
	var b strings.Builder
	b.WriteString("// Code generated by gen_blobs.go from RISC Zero's " +
		"bigint2 crate. DO NOT EDIT.\n")
	b.WriteString("//\n// The blobs are Apache-2.0 licensed RISC Zero " +
		"programs.\n\npackage bigint2\n")
	for _, blob := range blobs {
		raw, err := os.ReadFile(filepath.Join(os.Args[1], blob.path))
		if err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		if len(raw)%4 != 0 {
			fmt.Fprintf(os.Stderr, "%s is not word sized\n", blob.path)
			os.Exit(1)
		}
		sum := sha256.Sum256(raw)
		fmt.Fprintf(&b, "\n// %s is %s, SHA-256 %x.\n", blob.name,
			blob.path, sum)
		fmt.Fprintf(&b, "var %s = [...]uint32{", blob.name)
		for i := 0; i < len(raw); i += 4 {
			if i%24 == 0 {
				b.WriteString("\n\t")
			} else {
				b.WriteString(" ")
			}
			fmt.Fprintf(&b, "0x%08x,",
				binary.LittleEndian.Uint32(raw[i:]))
		}
		b.WriteString("\n}\n")
	}
	fmt.Print(b.String())
}
