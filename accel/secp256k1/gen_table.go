// gen_table writes generatorPowers, the affine points 2^i G for i in
// [0, 256), computed with math/big.
//
// Usage: go run gen_table.go > table.go
package main

import (
	"fmt"
	"math/big"
	"strings"
)

func hexInt(s string) *big.Int {
	v, ok := new(big.Int).SetString(s, 16)
	if !ok {
		panic(s)
	}
	return v
}

func words(v *big.Int) [8]uint32 {
	var out [8]uint32
	var buf [32]byte
	v.FillBytes(buf[:])
	for i := 0; i < 8; i++ {
		j := 28 - 4*i
		out[i] = uint32(buf[j])<<24 | uint32(buf[j+1])<<16 |
			uint32(buf[j+2])<<8 | uint32(buf[j+3])
	}
	return out
}

func main() {
	p := hexInt("fffffffffffffffffffffffffffffffffffffffffffffffffffffffefffffc2f")
	x := hexInt("79be667ef9dcbbac55a06295ce870b07029bfcdb2dce28d959f2815b16f81798")
	y := hexInt("483ada7726a3c4655da4fbfc0e1108a8fd17b448a68554199c47d08ffb10d4b8")

	var b strings.Builder
	b.WriteString("// Code generated by gen_table.go. DO NOT EDIT.\n\n")
	b.WriteString("package secp256k1\n\n")
	b.WriteString("// generatorPowers holds the affine points 2^i G.\n")
	b.WriteString("var generatorPowers = [256]point{\n")
	for i := 0; i < 256; i++ {
		wx, wy := words(x), words(y)
		b.WriteString("\t{xy: [16]uint32{")
		for j, w := range append(wx[:], wy[:]...) {
			if j > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "0x%08x", w)
		}
		b.WriteString("}},\n")

		// Double: l = 3x^2 / 2y.
		num := new(big.Int).Mul(x, x)
		num.Mul(num, big.NewInt(3))
		den := new(big.Int).Lsh(y, 1)
		den.ModInverse(den, p)
		l := num.Mul(num, den)
		l.Mod(l, p)
		nx := new(big.Int).Mul(l, l)
		nx.Sub(nx, x).Sub(nx, x).Mod(nx, p)
		ny := new(big.Int).Sub(x, nx)
		ny.Mul(ny, l).Sub(ny, y).Mod(ny, p)
		x, y = nx, ny
	}
	b.WriteString("}\n")
	fmt.Print(b.String())
}
