// Command gen writes vectors.go for the accel_selftest guest. It computes
// every expected value natively, with the standard library and the native
// (math/big) backend of the accel packages, whose own tests check them
// against the BIP-340 vectors and a math/big reference.
package main

import (
	"crypto/sha256"
	"encoding/csv"
	"fmt"
	"math/rand"
	"os"
	"strings"

	"github.com/roasbeef/go-zkvm/accel/secp256k1"
)

func main() {
	var b strings.Builder
	b.WriteString("// Code generated by gen/main.go. DO NOT EDIT.\n\n")
	b.WriteString("package main\n\n")

	b.WriteString("var shaVectors = []shaVector{\n")
	for _, n := range []int{0, 3, 55, 56, 63, 64, 65, 119, 120, 1000} {
		sum := sha256.Sum256(pattern(n))
		fmt.Fprintf(&b, "\t{%d, \"%x\"},\n", n, sum)
	}
	b.WriteString("}\n\n")

	f, err := os.Open("accel/secp256k1/testdata/bip340-vectors.csv")
	if err != nil {
		panic(err)
	}
	rows, err := csv.NewReader(f).ReadAll()
	if err != nil {
		panic(err)
	}
	b.WriteString("var schnorrVectors = []schnorrVector{\n")
	for _, row := range rows[1:] {
		fmt.Fprintf(&b, "\t{\"%s\", \"%s\", \"%s\", %v},\n",
			strings.ToLower(row[2]), strings.ToLower(row[4]),
			strings.ToLower(row[5]), row[6] == "TRUE")
	}
	b.WriteString("}\n\n")

	rng := rand.New(rand.NewSource(7))
	b.WriteString("var tweakVectors = []tweakVector{\n")
	for len := 0; len < 4; {
		var internal, tweak [32]byte
		rng.Read(internal[:])
		rng.Read(tweak[:])
		tweak[0] &= 0x7f
		out, odd, err := secp256k1.TweakAddXOnly(internal, tweak)
		if err != nil {
			continue
		}
		len++
		fmt.Fprintf(&b, "\t{\"%x\", \"%x\", \"%x\", %v},\n",
			internal, tweak, out, odd)
	}
	b.WriteString("}\n")
	fmt.Print(b.String())
}

func pattern(n int) []byte {
	out := make([]byte, n)
	for i := range out {
		out[i] = byte(i*7 + 3)
	}
	return out
}
